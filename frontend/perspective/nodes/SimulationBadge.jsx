"use client";

// Small, shared labels for the additive simulation fields returned by
// POST /api/perspective/simulate (simulated, generation, fallback_reason, model).

const FALLBACK_REASONS = {
  missing_key: 'No LLM API key is configured on the backend.',
  empty: 'The LLM returned an empty response.',
  error: 'The LLM request failed.',
};

export function describeFallbackReason(reason) {
  if (!reason) return 'The LLM was not used for this reaction.';
  return FALLBACK_REASONS[reason] || `Reason: ${reason}`;
}

// Returns { kind, label, title } for a reaction/turn/round, or null when unlabelled.
export function getGenerationLabel(item) {
  const generation = item?.generation;
  if (typeof generation !== 'string') return null;

  if (generation === 'llm') {
    return {
      kind: 'llm',
      label: 'LLM',
      title: item.model ? `Generated by an LLM (${item.model}).` : 'Generated by an LLM.',
    };
  }
  if (generation === 'fallback_template') {
    return {
      kind: 'fallback',
      label: 'template fallback',
      title: `Template text, not LLM output. ${describeFallbackReason(item.fallback_reason)}`,
    };
  }
  if (generation === 'template') {
    return {
      kind: 'template',
      label: 'template',
      title: 'Built from a fixed template, not LLM output.',
    };
  }
  return null;
}

// "2 LLM, 1 template fallback reactions; rounds: template" style summary of a node/result generation block.
export function summarizeGeneration(generation) {
  if (!generation || typeof generation !== 'object') return '';

  const parts = [];
  const reactions = generation.reactions;
  if (reactions && typeof reactions === 'object') {
    const llm = Number(reactions.llm) || 0;
    const fallback = Number(reactions.fallback_template) || 0;
    if (llm > 0) parts.push(`${llm} LLM`);
    if (fallback > 0) parts.push(`${fallback} template fallback`);
    if (parts.length > 0) parts[parts.length - 1] += ` reaction${llm + fallback === 1 ? '' : 's'}`;
  }
  const out = [];
  if (parts.length > 0) out.push(parts.join(', '));
  if (generation.rounds) out.push(`rounds: ${generation.rounds}`);
  if (generation.model) out.push(`model: ${generation.model}`);
  return out.join(' · ');
}

export function SimulationBadge({ data, className = '' }) {
  if (!data?.simulated) return null;
  const summary = summarizeGeneration(data.generation);
  const title = `Simulated persona roleplay, not observed community data.${summary ? ` ${summary}` : ''}`;
  return (
    <span className={`sim-badge ${className}`.trim()} title={title}>
      Simulated
    </span>
  );
}

export function GenerationTag({ item }) {
  const info = getGenerationLabel(item);
  if (!info) return null;
  return (
    <span className={`gen-tag gen-tag-${info.kind}`} title={info.title}>
      {info.label}
    </span>
  );
}

// Compact "who produced each reaction" row, for nodes that show rounds/turns instead of the reaction text.
export function ReactionSources({ reactions }) {
  const items = (Array.isArray(reactions) ? reactions : []).filter((r) => getGenerationLabel(r));
  if (items.length === 0) return null;
  return (
    <div className="node-reaction-sources">
      <span className="node-reaction-sources-label">Reactions:</span>
      {items.map((item, idx) => (
        <span key={`${item.persona || 'persona'}-${idx}`} className="node-reaction-source">
          {item.persona || 'Persona'} <GenerationTag item={item} />
        </span>
      ))}
    </div>
  );
}

// Safe 0..1 ideology distance; nodes receive both ideology_distance and ideologicalDistance.
export function readIdeologyDistance(data) {
  const candidates = [data?.ideology_distance, data?.ideologicalDistance];
  for (const value of candidates) {
    const n = typeof value === 'number' ? value : Number(value);
    if (value !== null && value !== undefined && value !== '' && Number.isFinite(n)) {
      return Math.max(0, Math.min(1, n));
    }
  }
  return null;
}
